// Latin slug; names without Latin letters (Arabic) get a stable short hash instead.
const evSlug = (s) => {
  const v = s.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
  if (/[a-z]/.test(v)) return v;
  let h = 0; for (const ch of s) h = (h * 31 + ch.codePointAt(0)) >>> 0;
  return 'n-' + h.toString(36);
};

