const PH_FILE = 'src/placeholders.json';
const phCache = fs.existsSync(PH_FILE) ? JSON.parse(fs.readFileSync(PH_FILE, 'utf8')) : {};
{
  const dir = (d, re) => fs.readdirSync(d).filter((f) => re.test(f)).map((f) => `${d}/${f}`);
  const want = [...dir('src/assets/img/work', /-cover-800\.webp$/), ...dir('src/assets/img/events', /-640\.webp$/), ...dir('src/assets/img/certificates', /-480\.webp$/), ...dir('src/assets/img/team', /-400\.webp$/)];
  const todo = want.filter((f) => !phCache[f] || phCache[f].m !== fs.statSync(f).mtimeMs);
  if (todo.length) {
    const sharp = (await import('sharp')).default;
    for (const f of todo) {
      const buf = await sharp(f).resize({ width: 20 }).webp({ quality: 50 }).toBuffer();
      phCache[f] = { m: fs.statSync(f).mtimeMs, d: 'data:image/webp;base64,' + buf.toString('base64') };
    }
    for (const k of Object.keys(phCache)) if (!want.includes(k)) delete phCache[k];
    fs.writeFileSync(PH_FILE, JSON.stringify(phCache));
  }
}
