const pack = (i) => ({
  html: HTML.map((r) => [r[0], r[i]]),
  dict: Object.fromEntries(TEXT.map((r) => [r[0], r[i]])),
  rules: RULES.map((r) => [r[0], r[i]]),
});

const TRANSLATED_ATTRS = ['alt', 'title', 'aria-label', 'placeholder', 'content', 'data-cursor', 'data-caption', 'data-label'];

const swapText = (text, dict, rules) => {
  const t = text.trim();
  if (!t) return text;
  let out = dict[t];
  if (out === undefined) for (const [re, rep] of rules) if (re.test(t)) { out = t.replace(re, rep); break; }
  return out === undefined ? text : text.replace(t, () => out);
};

export const translateHtml = (html, { html: frags, dict, rules }) => {
  for (const [a, b] of frags) html = html.split(a).join(b);
  // JSON-LD: translate string values only
  html = html.replace(/(<script type="application\/ld\+json">)([\s\S]*?)(<\/script>)/g, (m, a, json, b) => {
    try {
      const walk = (v) => (typeof v === 'string' ? swapText(v, dict, rules) : Array.isArray(v) ? v.map(walk) : v && typeof v === 'object' ? Object.fromEntries(Object.entries(v).map(([k, x]) => [k, walk(x)])) : v);
      return a + JSON.stringify(walk(JSON.parse(json))) + b;
    } catch { return m; }
  });
  // split into tags and text, leaving <script>/<style> bodies alone
  const parts = html.split(/(<script[\s\S]*?<\/script>|<style[\s\S]*?<\/style>|<[^>]+>)/);
  return parts.map((p, i) => {
    if (i % 2 === 0) return swapText(p, dict, rules);
    if (p.startsWith('<script') || p.startsWith('<style')) return p;
    return p.replace(/(\s)([a-z-]+)="([^"]*)"/g, (m, sp, k, v) => (TRANSLATED_ATTRS.includes(k) && v ? `${sp}${k}="${swapText(v, dict, rules)}"` : m));
  }).join('');
};

